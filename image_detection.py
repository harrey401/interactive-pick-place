def assign_ids_to_objects(objects_dict, detected_circles, id_next):
    """
    Assign IDs to the currently detected circles based on nearest match to existing objects.
    objects_dict: {id: {'x': x_mm, 'y': y_mm, 'r': r_mm, 'z': z_mm}}
    detected_circles: list of (x, y, r) in pixels
    id_next: the next ID number available if we need a new ID

    Returns: updated_objects_dict, updated_id_next
    """
    # Convert detected circles to mm
    detected_mm = []
    for (x, y, r) in detected_circles:
        x_mm = x * mm_per_pixel
        y_mm = y * mm_per_pixel
        r_mm = r * mm_per_pixel
        z_mm = 75  # fixed
        detected_mm.append((x_mm, y_mm, z_mm, r_mm))

    # If no existing objects, assign new IDs to all
    if not objects_dict:
        for circle in detected_mm:
            objects_dict[f"ID{id_next}"] = {'x': circle[0], 'y': circle[1], 'z': circle[2], 'r': circle[3]}
            id_next += 1
        return objects_dict, id_next

    # Otherwise, we attempt to match each detected object to an existing one
    unmatched_detections = detected_mm[:]
    updated_dict = {}

    # We'll use a greedy nearest-neighbor matching approach.
    # For each existing object, find the nearest detected circle.
    # Then remove that detected circle from the unmatched list.
    existing_ids = list(objects_dict.keys())

    # Attempt to match existing objects first
    for obj_id in existing_ids:
        obj_x = objects_dict[obj_id]['x']
        obj_y = objects_dict[obj_id]['y']
        obj_r = objects_dict[obj_id]['r']

        # Find closest match by Euclidean distance in (x,y,r) space
        # Although radius might not be as crucial for matching, we can still include it.
        # Primarily x,y should be enough for stable match, but we keep radius check minimal.
        best_match = None
        best_dist = float('inf')
        for (d_x, d_y, d_z, d_r) in unmatched_detections:
            dist = np.sqrt((d_x - obj_x)**2 + (d_y - obj_y)**2 + (d_r - obj_r)**2)
            if dist < best_dist:
                best_dist = dist
                best_match = (d_x, d_y, d_z, d_r)

        if best_match is not None:
            # Update the object with the matched detection
            updated_dict[obj_id] = {'x': best_match[0], 'y': best_match[1], 'z': best_match[2], 'r': best_match[3]}
            unmatched_detections.remove(best_match)

    # Now, assign new IDs to any unmatched detections
    for (d_x, d_y, d_z, d_r) in unmatched_detections:
        updated_dict[f"ID{id_next}"] = {'x': d_x, 'y': d_y, 'z': d_z, 'r': d_r}
        id_next += 1

    return updated_dict, id_next

