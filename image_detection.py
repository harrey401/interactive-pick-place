def process_video_for_squares(video_path, fps=5):
    """Process video to detect squares and output their centroids, z-coordinate, and rotation angles."""
    cap = cv2.VideoCapture(video_path)

    if not cap.isOpened():
        print("Error: Could not open video.")
        return

    # Get video properties
    video_fps = cap.get(cv2.CAP_PROP_FPS)
    frame_skip = int(video_fps / fps)  # Determine frames to skip for desired FPS

    frame_count = 0
    results = []  # Store the results for all frames

    while cap.isOpened():
        ret, frame = cap.read()
        if not ret:
            break

        # Process only frames at the specified rate
        if frame_count % frame_skip == 0:
            # Convert frame to grayscale
            gray_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

            # Apply Gaussian Blur to reduce noise
            blurred_frame = cv2.GaussianBlur(gray_frame, (9, 9), 2)

            # Apply binary thresholding
            _, binary_frame = cv2.threshold(blurred_frame, 100, 255, cv2.THRESH_BINARY)

            # Find contours
            contours, _ = cv2.findContours(binary_frame, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
            print(f"Frame {frame_count}: Detected {len(contours)} contours.")

            for contour in contours:
                # Approximate contour to a polygon
                epsilon = 0.04 * cv2.arcLength(contour, True)
                approx = cv2.approxPolyDP(contour, epsilon, True)

                # Check if the polygon is a square (4 sides and convex)
                if len(approx) == 4 and cv2.isContourConvex(approx):
                    area = cv2.contourArea(contour)
                    print(f"Frame {frame_count}: Detected square with area {area}.")
                    if 500 < area < 10000:  # Relaxed area filter
                        # Calculate centroid
                        moments = cv2.moments(contour)
                        if moments["m00"] == 0:
                            continue
                        cx = int(moments["m10"] / moments["m00"])
                        cy = int(moments["m01"] / moments["m00"])

                        # Estimate z-coordinate (placeholder logic)
                        z = 1 / np.sqrt(area) if area > 0 else 0

                        # Calculate rotation angle
                        rect = cv2.minAreaRect(contour)
                        box = cv2.boxPoints(rect)
                        box = np.int0(box)
                        top_right = sorted(box, key=lambda p: (p[0], -p[1]))[-1]
                        angle = np.degrees(np.arctan2(cy - top_right[1], top_right[0] - cx))

                        # Append results to the list
                        results.append({"Frame": frame_count, "x": cx, "y": cy, "z": z, "θ": angle})

        frame_count += 1

    cap.release()

    # Convert results to a DataFrame and display
    if results:
        df = pd.DataFrame(results)
        print("\nFinal Results (x, y, z, θ for each frame):")
        print(df)
    else:
        print("No valid squares detected in the video.")
    return results

