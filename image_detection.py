def process_usb_webcam_for_circles(camera_index=0, fps_interval=5):
    """
    Process USB webcam input to detect circles and output their centroids, radii, and depth.
    Only analyze one frame every `fps_interval` seconds.
    """
    # Open the USB webcam using the specified camera index (port from device manager)
    cap = cv2.VideoCapture(camera_index, cv2.CAP_DSHOW)
    if not cap.isOpened():
        print(f"Error: Could not access the webcam on port {camera_index}.")
        return

    stationary_objects = []  # To store stationary x, y, z, and radius values
    last_detected = None  # Store the previous frame's detected circles
    last_written_location = None  # Track the last written constant location

    print("Press 'q' to quit.")

    while True:
        start_time = time.time()
        ret, frame = cap.read()
        if not ret:
            print("Error: Could not read frame from the webcam.")
            break

        # Convert frame to grayscale
        gray_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

        # Apply Gaussian Blur to reduce noise
        blurred_frame = cv2.GaussianBlur(gray_frame, (9, 9), 2)

        # Detect circles using Hough Circle Transform
        circles = cv2.HoughCircles(
            blurred_frame,
            cv2.HOUGH_GRADIENT,
            dp=1.2,  # Inverse ratio of the accumulator resolution to the image resolution
            minDist=50,  # Minimum distance between circle centers
            param1=50,  # Upper threshold for Canny edge detection
            param2=30,  # Threshold for center detection
            minRadius=10,  # Minimum circle radius
            maxRadius=100  # Maximum circle radius
        )

        if circles is not None:
            circles = np.round(circles[0, :]).astype("int")  # Round and convert to integer
            for (x, y, r) in circles:
                # Convert coordinates and radius to millimeters
                x_mm = x * mm_per_pixel
                y_mm = y * mm_per_pixel
                r_mm = r * mm_per_pixel
                z_mm = 75  # Set z to 75 mm for stationary objects

                # Check if the object is stationary (detected in two consecutive frames)
                if last_detected is not None:
                    for (prev_x, prev_y, prev_r) in last_detected:
                        if abs(prev_x - x) < 5 and abs(prev_y - y) < 5 and abs(prev_r - r) < 5:
                            # Object considered stationary
                            location_line = f"x={x_mm:.2f}, y={y_mm:.2f}, z={z_mm:.2f}, radius={r_mm:.2f}"
                            if location_line != last_written_location:  # Only write if location is different
                                stationary_objects.append(location_line)
                                last_written_location = location_line  # Update the last written location
                                print(f"Stationary Object: {location_line}")

                # Draw the circle and centroid on the frame
