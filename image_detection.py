                cv2.putText(frame, f"x={x_mm:.2f} mm, y={y_mm:.2f} mm, r={r_mm:.2f} mm, z={z_mm:.2f} mm",
                            (x - 50, y - r - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 1)

